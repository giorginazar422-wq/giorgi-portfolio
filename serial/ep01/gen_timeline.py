# Черновой тайминг слов (оценка по длине слов). После записи голоса заменить на точный (выравнивание).
import json,re
P=[(0.8,4.0,"Сегодня в небе появилась вторая луна."),(5.0,6.8,"Вчера её не было."),
(9.5,13.5,"Я сторож. Моя работа — ничего не замечать."),(14.2,17.2,"Но приборы замечали уже неделю."),
(18.5,20.8,"Я думал, они сломались."),(23.5,29.0,"Ночью позвонил доктор Ким, единственный астроном, который здесь работает."),
(29.8,31.5,"Он не поздоровался."),(32.5,39.5,"Он сказал: «Артём, это не луна. Это камень. Семьдесят два часа»."),
(41.0,42.8,"Я вышел во двор."),(43.5,44.8,"Город спал."),(45.5,47.5,"Никто не поднимал головы."),
(48.5,51.0,"Я хотел крикнуть, но кому?"),(52.5,56.3,"Доктор сказал ещё одно: «Он не падает."),
(57.6,59.2,"Он тормозит»."),(60.3,62.0,"Камни не тормозят."),(63.0,65.5,"Я смотрел и считал секунды."),
(66.5,69.5,"А потом на нём загорелся свет.")]
KEY={"луна","камень","семьдесят","два","часа","тормозит","свет","вчера","сторож"}
words=[]
for pi,(a,b,txt) in enumerate(P):
    ws=txt.split();wt=[len(re.sub(r'\W','',w))+2 for w in ws];tot=sum(wt);t=a
    for w,x in zip(ws,wt):
        d=(b-a)*x/tot
        c=re.sub(r'[^\w]','',w.lower())
        words.append(dict(w=w,s=round(t,3),e=round(t+d*0.92,3),p=pi,key=c in KEY));t+=d
json.dump(words,open('timeline.json','w'),ensure_ascii=False,indent=1)
open('art/timeline.js','w').write('const TL='+json.dumps(words,ensure_ascii=False)+';')
print(len(words),'слов, до',words[-1]['e'],'с')
